public class NilaiMahasiswaLv1 {
    public static void main(String[] args) {
        
        //Buat array int untuk menyimpan lima nilai: 80, 75, 90, 65, dan 85
        int nilai [] = {80, 75, 90, 65, 85};


        //Tampilkan seluruh nilai menggunakan perulangan 
        System.out.print("Seluruh nilai: ");
        for (int i = 0; i < nilai.length; i++); {
            System.out.print(nilai[1] + " ");
        }
        System.out.println();

        //Tampilkan nilai mahasiswa pada indeks ke-2
        System.out.println("Nilai pada indeks ke-2: " + nilai[2]);
    }
}
